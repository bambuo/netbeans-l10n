#!/usr/bin/env python3
"""Generate cnb-map.properties: <cluster>/<moduleDir> -> real code-name-base.

The translation tree mirrors the git layout (<cluster>/<moduleDir>/src/<pkg>/),
but a module's code-name-base cannot always be derived from its directory name
(e.g. core.ui -> org.netbeans.core.ui, not org.netbeans.modules.core.ui).
This script derives the authoritative mapping from the built IDE by matching
translation packages to the module jars that actually contain them.
"""
import io
import os
import zipfile
from collections import Counter, defaultdict

from paths import BUILD, TREE, CNB_MAP

OUT = CNB_MAP


def main():
    # package -> candidate (cluster, cnb) taken from real module jars
    pkg2jar = defaultdict(Counter)
    for cluster in sorted(os.listdir(BUILD)):
        mdir = os.path.join(BUILD, cluster, "modules")
        if not os.path.isdir(mdir):
            continue
        for fn in sorted(os.listdir(mdir)):
            if not fn.endswith(".jar"):
                continue
            try:
                z = zipfile.ZipFile(os.path.join(mdir, fn))
            except Exception:
                continue
            for e in z.namelist():
                if e.endswith("/Bundle.properties") or e == "Bundle.properties":
                    pkg = e[: e.rfind("/")] if "/" in e else ""
                    pkg2jar[pkg][cluster + "/" + fn[:-4]] += 1
            z.close()

    votes = defaultdict(Counter)   # (cluster, moduleDir) -> Counter(cnb)
    # real (cluster, cnb) pairs that actually ship, used to reject bogus guesses
    existing = defaultdict(set)
    for cluster in os.listdir(BUILD):
        mdir = os.path.join(BUILD, cluster, "modules")
        if os.path.isdir(mdir):
            for fn in os.listdir(mdir):
                if fn.endswith(".jar"):
                    existing[cluster].add(fn[:-4])

    def naive_cnb(module_dir):
        return "org-netbeans-modules-" + module_dir.replace(".", "-")

    for root, dirs, files in os.walk(TREE):
        for fn in files:
            if not fn.endswith("_zh_CN.properties"):
                continue
            rel = os.path.relpath(os.path.join(root, fn), TREE).replace(os.sep, "/")
            if "/src/" not in rel:
                continue
            cluster, module_dir = rel.split("/")[0], rel.split("/")[1]
            pkg = rel.split("/src/", 1)[1]
            pkg = pkg[: pkg.rfind("/")] if "/" in pkg else ""
            naive = naive_cnb(module_dir)
            dir_suffix = module_dir.replace(".", "-")
            for target, n in pkg2jar.get(pkg, {}).items():
                t_cluster, t_cnb = target.split("/", 1)
                if t_cnb not in existing.get(t_cluster, ()):
                    continue
                weight = n * 4 if t_cluster == cluster else n
                # directory name is strong evidence: prefer the module whose
                # code-name-base matches its directory (fixes terminal vs
                # terminal.nb, java.platform vs java.platform.ui, ...)
                if t_cluster == cluster:
                    if t_cnb == naive:
                        weight += 10000
                    elif t_cnb.endswith("-" + dir_suffix) or \
                            t_cnb.endswith("." + module_dir):
                        weight += 5000
                votes[(cluster, module_dir)][t_cnb] += weight

    lines = [
        "# Mapping of translation-tree module directories to NetBeans code-name-bases.",
        "# Generated by l10n-check/gen_cnb_map.py from the built IDE; do not edit by hand.",
    ]
    resolved = 0
    for (cluster, module_dir), counter in sorted(votes.items()):
        if not counter:
            continue
        cnb, _ = counter.most_common(1)[0]
        lines.append("%s/%s=%s" % (cluster, module_dir, cnb))
        resolved += 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("#SUMMARY mapped_module_dirs=%d -> %s" % (resolved, OUT))

    # report collisions: several module dirs claiming one cnb in the same cluster
    rev = defaultdict(list)
    for l in lines[2:]:
        k, v = l.split("=", 1)
        rev[v].append(k)
    clashes = {k: v for k, v in rev.items() if len(v) > 1}
    print("#SUMMARY cnb_collisions=%d" % len(clashes))
    for k, v in sorted(clashes.items())[:10]:
        print("COLLISION %s <- %s" % (k, ", ".join(v)))


if __name__ == "__main__":
    main()
